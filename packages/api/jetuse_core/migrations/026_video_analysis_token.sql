-- VID-02 分析の権利の印(specs/20 §3「同時実行の範囲」)。
--
-- `analysis_state <> 'running'` だけを入口の条件にすると、分析中に落ちた映像が
-- `running` のまま固まって二度と再分析できない。そこで 025 の `analysis_started_at` で
-- 「十分に古い running は引き継いでよい」と言えるようにした。
--
-- ただし**引き継ぎは相手が落ちていることを保証しない**(単に遅いだけかもしれない)。
-- 生きたまま引き継がれた古い実行がそのまま台帳を書き続けると、新しい実行の場面を
-- 上書きし、その `running` まで解いて 3 本目の開始を許す ＝「同時に 1 つだけ」が破れる。
-- 権利を取るたびに新しい印を書き、以降の書き込みはこの印が一致するときだけ通す。
--
-- **時刻(`analysis_started_at`)を印に流用しない。** python-oracledb は datetime を
-- 既定で DATE として束縛するので、`TIMESTAMP(6)` 列との等値比較が小数秒の欠落で
-- 静かに 0 件になる(実測)。`setinputsizes` で回避はできるが、書き忘れた瞬間に
-- **フェンスが黙って効かなくなる**。文字列なら型の取り違えが起きない。
--
-- **1 文だけにする**(024 / 025 と同じ理由)。NULL は「まだ一度も分析を始めていない」。

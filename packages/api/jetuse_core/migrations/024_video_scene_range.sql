-- VID-02 場面の時間区間を「実測から作った正しい区間」だけに絞る。
--
-- 023 の `end_ms >= start_ms` は**負の開始時刻とゼロ長の場面を通す**。どちらも
-- 場面を実際に作る VID-02 で作れてはいけない値:
--   * `start_ms < 0` … タイムライン(specs/20 §6)が映像の外に帯を描き、
--     `/videos/{id}?t=<秒>` が負の時刻でプレーヤに渡る
--   * `end_ms = start_ms` … 幅ゼロの帯は掴めず、その場面は「再生して確かめる」ができない
-- 場面の境界は ffmpeg の実測から作る(ADR-0032 決定3)ので、この2つが出るのは
-- 実装の誤りであり、DB で落として気づけるようにする。
--
-- **023 は適用済みなので書き換えない**(schema_migrations の記録と食い違う)。足す。
--
-- **1 文だけにする。** 023 の制約は落とさず、厳しい方を隣に足すだけにしてある。
-- 理由は 2 つ:
--   1. DROP → ADD の 2 文にすると、ADD が失敗した瞬間(既存行が新しい制約に反する等)に
--      **制約の無い表が残る**。Oracle の DDL は 1 文ごとに暗黙 commit されるので、
--      この隙間はトランザクションでは塞げない。
--   2. 2 文の間で接続が切れると「片方だけ適用され、schema_migrations には記録が無い」
--      状態になり、再実行が別の理由で落ちる。1 文なら**適用されたか、されていないか**の
--      2 状態しかない。
-- 残る `video_scenes_range_ck`(`end_ms >= start_ms`)は新しい制約に含意されるので、
-- 両方が有効でも矛盾しない。名前を変えるのは、同じ表に同名の制約を 2 つ置けないため
-- (意味は「区間は正の幅を持つ」)。
ALTER TABLE video_scenes ADD CONSTRAINT video_scenes_span_ck
  CHECK (start_ms >= 0 AND end_ms > start_ms)
